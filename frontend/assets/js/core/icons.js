// Auto-render helper for elements with data-kma-icon attribute
function initKMAIcons() {
  if (typeof document === 'undefined') return;
  const elements = document.querySelectorAll('[data-kma-icon]');
  elements.forEach(el => {
    const iconName = el.getAttribute('data-kma-icon');
    const size = parseInt(el.getAttribute('data-kma-size'), 10) || 20;
    const color = el.getAttribute('data-kma-color') || 'currentColor';
    if (typeof KMAIcons[iconName] === 'function') {
      el.innerHTML = KMAIcons[iconName](size, color);
    }
  });
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initKMAIcons);
  } else {
    initKMAIcons();
  }
}

